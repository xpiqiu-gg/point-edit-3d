export function translate(value:string, language:Language):string {
  if(language!=='en') return value;
  if(en[value]) return en[value];
  const patterns: [RegExp,(...args:string[])=>string][] = [
    [/^已读取 (C4D|Blender) 当前场景 · (\d+) 个对象$/,(_m,source,n)=>`Loaded ${source} scene · ${n} objects`],
    [/^(C4D|Blender) 已连接 · (\d+) 个编号已匹配$/,(_m,source,n)=>`${source} connected · ${n} IDs matched`],
    [/^无法解析 (C4D|Blender) 预览模型$/,(_m,source)=>`Could not parse the ${source} preview`],
    [/^无法读取 (C4D|Blender) 预览$/,(_m,source)=>`Could not load the ${source} preview`],
    [/^正在检查 (C4D|Blender) 连接…$/,(_m,source)=>`Checking ${source} connection…`],
    [/^(C4D|Blender) 未连接或插件版本未更新$/,(_m,source)=>`${source} is disconnected or the plugin is outdated`],
    [/^(C4D|Blender) 已连接，场景身份不匹配$/,(_m,source)=>`${source} connected, but the scene identity does not match`],
  ];
  for(const [pattern,fn] of patterns) { const match=value.match(pattern); if(match) return fn(...match); }
  return value;
}

export async function loadLanguage():Promise<Language> {
  const response=await fetch('/__point_edit_3d/language',{headers:{'X-Point-Edit':'language'}});
  if(!response.ok) throw new Error('Cannot load language');
  return (await response.json()).language === 'en' ? 'en' : 'zh';
}
export async function saveLanguage(language:Language) {
  const response=await fetch('/__point_edit_3d/language',{method:'POST',headers:{'Content-Type':'application/json','X-Point-Edit':'language'},body:JSON.stringify({language})});
  if(!response.ok) throw new Error(language==='en' ? 'Could not save language settings' : '语言设置未能保存');
}
